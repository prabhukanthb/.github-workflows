const PRIVATE_PREFIXES = ['/admin', '/browse', '/profile', '/interests', '/login', '/forgot-password', '/change-password'];

export function normalizePath(pathname) {
  const path = String(pathname || '/').split('?')[0].replace(/\/+$/, '') || '/';
  return path;
}

export function landingFor(pathname) {
  const path = normalizePath(pathname);
  return LANDINGS.find((page) => page.path === path) || null;
}

export function pageFor(pathname) {
  const path = normalizePath(pathname);
  const landing = landingFor(path);
  if (landing) return { index: true, ...landing };
  if (PAGES[path]) return { path, ...PAGES[path] };
  return {
    path,
    title: 'Telugu Kalyanamala',
    description: PAGES['/'].description,
    index: false,
    priority: '0.0'
  };
}

export function isPrivatePath(pathname) {
  const path = normalizePath(pathname);
  return PRIVATE_PREFIXES.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));
}

export function publicPages() {
  const pages = Object.entries(PAGES)
    .filter(([, page]) => page.index)
    .map(([path, page]) => ({ path, ...page }));
  return [...pages, ...LANDINGS.map((page) => ({ index: true, ...page }))];
}
